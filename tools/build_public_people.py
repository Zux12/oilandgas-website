"""Build public author profiles, publication and article pages, and the sitemap."""
import hashlib
import json
import re
import time
import unicodedata
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor
from html import escape
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import quote, urlencode, urlsplit, parse_qs
from urllib.request import urlopen
from urllib.error import URLError
import xml.etree.ElementTree as ET

from homepage_brief import update_homepage, apply_manual_picks

ROOT = Path(__file__).resolve().parents[1]
SITE = 'https://oilandgas.eu.com'
FEED = 'https://mterm2026-559f9bf571b5.herokuapp.com/api/oilandgas/editor/browse'
FOLDERS = {'articles': 'articles', 'publications': 'papers'}
PATHS = 'entry-paths.json'
OWNER = '<!-- Generated by build_public_people.py -->'
START = '<!-- Additional credited works: start -->'
END = '<!-- Additional credited works: end -->'
ZURIX_PAGE = '/m-zurix-mohamed.html'
SEPARATOR = re.compile(r'\s*[,;]\s*|\s+(?:and|&)\s+', re.I)
GROUPS = {'oil & gas editorial', 'oil and gas editorial', 'editorial team', 'anonymous',
          'unknown', 'n/a', 'et al.', 'et al', 'staff', 'editorial', 'various authors'}


def key(name):
    name = ' '.join(unicodedata.normalize('NFC', name).casefold().split())
    return re.sub(r'(?<!\w)([^\W\d_])\.(?=\s|$)', r'\1', name)


def public_name(name):
    return bool(name.strip() and key(name) not in GROUPS and '@' not in name
                and '://' not in name and not re.search(r'[<>]', name) and any(ch.isalpha() for ch in name))


def slug(name):
    plain = unicodedata.normalize('NFKD', name).encode('ascii', 'ignore').decode()
    return re.sub(r'[^a-z0-9]+', '-', plain.lower()).strip('-')[:65] or 'author'


def get_json(url):
    # Retry brief network outages; fail closed so incomplete builds cannot overwrite public pages.
    for attempt in range(3):
        try:
            with urlopen(url, timeout=30) as response:
                return json.load(response)
        except (URLError, TimeoutError):
            if attempt == 2:
                raise
            time.sleep(2 ** attempt)


def load_entries():
    entries = {}
    for kind in ('articles', 'publications'):
        page = 0
        while True:
            query = urlencode({'kind': kind, 'page': page, 'limit': 24})
            listing = get_json(FEED + '?' + query)
            items, more = listing['items'], listing['more']
            if not isinstance(items, list) or not isinstance(more, bool) or (more and len(items) != 24):
                raise ValueError('Incomplete public listing')
            for item in items:
                ref = item['reference']
                if (item['kind'] != kind or not isinstance(ref, str) or not ref.strip()
                        or ref in entries or not isinstance(item['byline'], str)
                        or not isinstance(item['title'], str) or not item['title'].strip()):
                    raise ValueError(f'Invalid or duplicate public record: {ref}')
                entries[ref] = item
            if not more:
                break
            page += 1
    # The public listing carries complete paper records. Article text is on the detail endpoint.
    articles = [e for e in entries.values() if e['kind'] == 'articles']
    with ThreadPoolExecutor(max_workers=4) as pool:
        for article in pool.map(load_article, articles):
            entries[article['reference']] = article
    return entries


def load_article(listed):
    endpoint = FEED.rsplit('/', 1)[0] + '/published/articles/' + quote(listed['reference'], safe='')
    article = get_json(endpoint)
    if (article.get('reference') != listed['reference'] or article.get('kind') != 'articles'
            or not isinstance(article.get('byline'), str) or not article.get('title')
            or 'body' not in article or not isinstance(article['body'], (str, type(None)))):
        raise ValueError(f"Incomplete published article: {listed['reference']}")
    return article


def entry_paths(entries, root):
    # Retain the first published URL even after an editor corrects the title.
    file = root / PATHS
    previous = json.loads(file.read_text()) if file.exists() else {}
    paths = {}
    for ref, entry in sorted(entries.items()):
        folder = FOLDERS[entry['kind']]
        token = ref.lower() if re.fullmatch('[a-zA-Z0-9-]{1,64}', ref) else hashlib.sha256(ref.encode()).hexdigest()
        path = previous.get(ref, f'/{folder}/{slug(entry["title"])}--{token}.html')
        if not re.fullmatch(rf'/{folder}/[a-z0-9-]+--{token}\.html', path):
            raise ValueError(f'Invalid permanent path for {ref}')
        paths[ref] = path
    if len(set(paths.values())) != len(paths):
        raise ValueError('Duplicate permanent page paths')
    return paths


def shell(title, description, url, main, profile_name=None, entry=None):
    schema = ''
    if profile_name:
        data = {'@context': 'https://schema.org', '@type': 'ProfilePage', 'url': SITE + url,
                'mainEntity': {'@type': 'Person', '@id': SITE + url + '#person', 'name': profile_name}}
        payload = json.dumps(data, ensure_ascii=False).replace('<', r'\u003c')
        schema = f'<script type="application/ld+json">{payload}</script>'
    if entry:
        date = str(entry.get('publishedAt') or '')[:10]
        names = [n.strip() for n in re.split(r'\s*[,;]\s*|\s+(?:and|&)\s+', entry.get('byline', ''), flags=re.I) if public_name(n)]
        data = {'@context': 'https://schema.org',
                '@type': 'ScholarlyArticle' if entry['kind'] == 'publications' else 'Article',
                'headline': title, 'description': description, 'url': SITE + url,
                'mainEntityOfPage': SITE + url,
                'publisher': {'@type': 'Organization', 'name': 'Oil & Gas Community', 'url': SITE},
                'author': [{'@type': 'Person', 'name': name} for name in names]}
        if re.fullmatch(r'\d{4}-\d{2}-\d{2}', date):
            data['datePublished'] = date
        source = entry.get('source') or ''
        if entry['kind'] == 'publications' and re.match(r'^https?://[^/\s]+', source, re.I):
            data['sameAs'] = source
        schema += '<script type="application/ld+json">' + json.dumps(data, ensure_ascii=False).replace('<', r'\u003c') + '</script>'
    card_type = 'article' if entry else 'profile' if profile_name else 'website'
    social = ('<meta property="og:type" content="' + card_type + '">'
              '<meta property="og:title" content="' + escape(title, quote=True) + '">'
              '<meta property="og:description" content="' + escape(description[:300], quote=True) + '">'
              '<meta property="og:url" content="' + escape(SITE + url, quote=True) + '">'
              '<meta property="og:image" content="' + SITE + '/logo.png">'
              '<meta name="twitter:card" content="summary">')
    return f'''<!doctype html>
<html lang="en">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{escape(title)} | Oil &amp; Gas</title>
<meta name="description" content="{escape(description)}"><link rel="canonical" href="{escape(SITE + url)}">
<link rel="stylesheet" href="/browse.css"><link rel="stylesheet" href="/people.css">{social}{schema}</head>
<body>{OWNER}
<header class="wrap"><div class="brand"><a href="/"><img src="/logo.png" alt="Oil &amp; Gas home"></a></div>
<nav class="nav people-nav" aria-label="Main navigation"><a href="/">Home</a>
<a href="/browse.html?kind=publications">Publications</a><a href="/browse.html?kind=articles">Articles</a>
<a href="/authors/">Authors &amp; contributors</a></nav></header>
<main class="people">{main}</main></body></html>
'''


def work_sections(works, paths):
    sections = []
    for role, title in [('publications', 'Publications'), ('articles', 'Articles'), ('shared', 'Shared works')]:
        if not works.get(role):
            continue
        rows = []
        for entry in sorted(works[role], key=lambda e: (e.get('publishedAt') or '', e['reference']), reverse=True):
            url = escape(paths[entry['reference']])
            byline = escape(entry['byline'])
            desc = escape(entry.get('summary') or '')
            rows.append(f'<li><h3><a href="{url}">{escape(entry["title"])}</a></h3>'
                        f'<p class="byline">{byline}</p><p>{desc}</p></li>')
        sections.append(f'<section><h2>{title}</h2><ul class="works">{"".join(rows)}</ul></section>')
    return '\n'.join(sections)


class CuratedLinks(HTMLParser):
    def __init__(self):
        super().__init__()
        self.reader_links = {}
        self.paths = set()

    def handle_starttag(self, tag, attrs):
        if tag == 'a':
            href = dict(attrs).get('href') or ''
            url = urlsplit(href)
            if not url.netloc and url.path.lstrip('/') == 'read.html':
                refs = parse_qs(url.query).get('ref', [])
                if refs:
                    self.reader_links[href] = refs[0]
            self.paths.add(url.path)


def extend_zurix_page(original, works, paths):
    # Preserve the editor's selection, biography, design and already indexed URL.
    if START in original and END in original:
        before, rest = original.split(START, 1)
        original = before + rest.split(END, 1)[1]
    if original.count('</main>') != 1:
        raise ValueError('Expected one main section in the existing Zurix profile')
    curated = CuratedLinks()
    curated.feed(original)
    for old, ref in curated.reader_links.items():
        if ref in paths:
            original = original.replace(f'href="{escape(old)}"', f'href="{paths[ref]}"')
            curated.paths.add(paths[ref])
    remaining = {k: [e for e in items if paths[e['reference']] not in curated.paths]
                 for k, items in works.items()}
    block = START + '\n' + work_sections(remaining, paths) + '\n' + END
    return original.replace('</main>', block + '</main>')


def credit_link(label, links):
    path = links.get(label.strip())
    return f'<a href="{escape(path)}">{escape(label)}</a>' if path else escape(label)


def render_work(entry, credit, path):
    paper = entry['kind'] == 'publications'
    parts = re.split(r'(,\s*|;\s*|\s+(?:and|&)\s+)', entry['byline'], flags=re.I)
    byline = ''.join(credit_link(part, credit['authors']) for part in parts)
    topics = [entry.get('topic'), 'Technology Across Industries' if entry.get('crossIndustry') else None]
    label = 'Research publication' if paper else 'Article'
    tags = ' · '.join(escape(t) for t in [label, *topics] if t)
    main = [f'<article class="entry"><p class="eyebrow">{tags}</p>',
            f'<h1>{escape(entry["title"])}</h1>', f'<p class="byline">{byline}</p>']
    date = str(entry.get('publishedAt') or '')[:10]
    if re.fullmatch(r'\d{4}-\d{2}-\d{2}', date):
        main.append(f'<p class="publication-date">Published on Oil &amp; Gas: <time datetime="{date}">{date}</time></p>')
    main.append('<div class="publication-actions"><button type="button" class="copy-publication-link" data-copy-link>Copy page link</button><span class="copy-link-result" role="status" aria-live="polite"></span></div>')
    if entry.get('sharedBy'):
        main.append('<p>Shared by ' + credit_link(entry['sharedBy'], credit['shared']) + '</p>')
    summary = entry.get('summary') or ''
    if summary:
        main.append(f'<h2>Summary</h2><p>{escape(summary)}</p>')
    if not paper:
        paragraphs = re.split(r'\r?\n[ \t]*\r?\n', entry.get('body') or '')
        main.append('<h2>Full article</h2>')
        main.extend(f'<p class="article-text">{escape(part)}</p>' for part in paragraphs if part.strip())
        if not any(part.strip() for part in paragraphs):
            main.append('<p>The full text is unavailable for this article.</p>')
    source = entry.get('source') or ''
    if re.match(r'^https?://[^/\s]+', source, re.I):
        label = 'Read original paper' if paper else 'Read original source'
        main.append(f'<p><a href="{escape(source)}" rel="noopener noreferrer">{label}</a></p>')
    main.append('</article>')
    page = shell(entry['title'], summary or entry['title'], path, '\n'.join(main), entry=entry)
    return page.replace('</body>', '<script src="/publication-actions.js" defer></script></body>')


def make_outputs(entries, config, root=ROOT):
    paths = entry_paths(entries, root)
    profiles = config['profiles']
    # Public members are explicit editorial entries, never fetched from registration data.
    members = config['public_members']
    aliases = {}
    urls = {}
    names = {}
    bios = {}
    for identifier, info in list(profiles.items()) + [(m['id'], m) for m in members]:
        if (not re.fullmatch('[a-z0-9][a-z0-9-]*', identifier) or identifier == 'index'
                or identifier in names or not public_name(info['name'])):
            raise ValueError(f'Invalid profile configuration: {identifier}')
        names[identifier] = info['name']
        urls[identifier] = ZURIX_PAGE if identifier == 'zurix' else f'/authors/{identifier}.html'
        bios[identifier] = info.get('bio', '').strip()
        for value in [info['name'], *info.get('aliases', [])]:
            # If two people have the same name, require explicit per-record resolution.
            alias = key(value)
            aliases[alias] = identifier if alias not in aliases or aliases[alias] == identifier else None

    works = defaultdict(lambda: defaultdict(list))
    credits = {}
    indexable = {SITE + '/', SITE + '/authors/'}
    for page in ('contact.html', 'membership.html'):
        if (root / page).is_file():
            indexable.add(f'{SITE}/{page}')
    indexable.update(SITE + '/browse.html?kind=' + k for k in ('articles', 'publications'))
    overrides = config['credit_overrides']
    configured_ids = set(names)
    for ref, item in sorted(entries.items()):
        indexable.add(SITE + paths[ref])
        byline = item['byline'].strip()
        listed = [name for group in re.split(r'[,;]', byline) if key(group) not in GROUPS
                  for name in SEPARATOR.split(group)]
        credit = {'authors': {}, 'shared': {}}
        seen = set()
        for role, labels in [('authors', listed), ('shared', [item.get('sharedBy') or ''])]:
            for raw in labels:
                label = raw.strip()
                if not public_name(label):
                    continue
                normalized = key(label)
                item_override = overrides.get(ref, {}).get(label)
                if item_override is not None:
                    if item_override not in configured_ids:
                        raise ValueError(f'Unknown profile for {ref}: {item_override}')
                    identifier = item_override
                elif normalized in aliases:
                    identifier = aliases[normalized]
                    if identifier is None:
                        continue
                else:
                    identifier = 'name:' + normalized
                    if identifier not in urls:
                        suffix = hashlib.sha256(normalized.encode()).hexdigest()[:12]
                        urls[identifier] = f'/authors/{slug(normalized)}-{suffix}.html'
                        names[identifier] = label
                credit[role][label] = urls[identifier]
                if identifier not in seen:
                    works[identifier][item['kind'] if role == 'authors' else 'shared'].append(item)
                    seen.add(identifier)
        credits[ref] = credit

    for member in members:
        if not bios[member['id']]:
            raise ValueError('A public member needs a short public biography')
        works[member['id']]  # Include the profile even before their first publication.
    outputs = {PATHS: json.dumps(paths, indent=2, ensure_ascii=False) + '\n'}
    for ref, item in entries.items():
        path = paths[ref]
        outputs[path[1:]] = render_work(item, credits[ref], path)
    people = sorted(works, key=lambda i: (key(names[i]), i))
    member_ids = {m['id'] for m in members}
    for identifier in people:
        url = urls[identifier]
        name = names[identifier]
        indexable.add(SITE + url)
        if identifier == 'zurix':
            continue
        if url[1:] in outputs:
            raise ValueError(f'Conflicting profile URL: {url}')
        credits_here = works[identifier]
        caption = 'Author' if credits_here.get('articles') or credits_here.get('publications') else (
            'Member' if identifier in member_ids else 'Contributor')
        bio = bios.get(identifier) or ''
        first_work = next((e['title'] for items in credits_here.values() for e in items), '')
        description = bio or f'{caption} {name}. {first_work}'
        main = f'<p class="eyebrow">{caption}</p><h1>{escape(name)}</h1>'
        if bio:
            main += f'<p>{escape(bio)}</p>'
        outputs[url[1:]] = shell(name, description, url, main + work_sections(credits_here, paths), name)
    existing = root / ZURIX_PAGE[1:]
    if existing.is_file():
        indexable.add(SITE + ZURIX_PAGE)
        outputs[ZURIX_PAGE[1:]] = extend_zurix_page(existing.read_text(), works.get('zurix', {}), paths)
    elif 'zurix' in works:
        raise ValueError('The existing indexed Zurix page is missing')
    rows = [f'<li><a href="{urls[i]}">{escape(names[i])}</a></li>' for i in people]
    directory = ('<h1>Authors &amp; contributors</h1>'
                 '<div class="directory-tools"><label for="author-search">Find an author or contributor</label>'
                 '<input id="author-search" type="search" autocomplete="off" '
                 'placeholder="Search by name" aria-controls="author-directory" maxlength="160">'
                 '<p id="author-count" role="status" aria-live="polite"></p></div>'
                 '<ul class="directory" id="author-directory">' + ''.join(rows) + '</ul>'
                 '<p id="author-empty" hidden>No matching authors. Try a different name.</p>'
                 '<script src="/author-directory.js" defer></script>')
    outputs['authors/index.html'] = shell('Authors & contributors', 'Find authors, contributors and their published work on Oil & Gas.',
                                          '/authors/', directory)
    outputs['authors/credits.json'] = json.dumps(credits, ensure_ascii=False, sort_keys=True, indent=2) + '\n'
    if len(indexable) > 50000:
        raise ValueError('The sitemap must now be split into multiple files')
    xml = ET.Element('urlset', xmlns='http://www.sitemaps.org/schemas/sitemap/0.9')
    for url in sorted(indexable):
        ET.SubElement(ET.SubElement(xml, 'url'), 'loc').text = url
    ET.indent(xml)
    outputs['sitemap.xml'] = ET.tostring(xml, encoding='utf-8', xml_declaration=True).decode()
    return outputs


def save(outputs, root=ROOT):
    folders = ('authors', *FOLDERS.values())
    obsolete = []
    for name in folders:
        folder = root / name
        folder.mkdir(exist_ok=True)
        obsolete.extend(path for path in folder.glob('*.html')
                        if path.relative_to(root).as_posix() not in outputs and OWNER in path.read_text())
    for path in outputs:
        old = root / path
        if old.parent.name in folders and old.suffix == '.html' and old.exists() and OWNER not in old.read_text():
            raise ValueError(f'Existing hand-written page would be overwritten: {path}')
    for path, body in outputs.items():
        (root / path).write_text(body, encoding='utf-8')
    for path in obsolete:
        path.unlink()


if __name__ == '__main__':
    data = load_entries()
    cfg = json.loads((ROOT / 'tools/public-people.json').read_text())
    outputs = make_outputs(data, cfg)
    issue = json.loads((ROOT / 'editorial/weekly-brief.json').read_text())
    issue = apply_manual_picks(issue, get_json(FEED.rsplit('/', 1)[0] + '/weekly-picks'), data)
    outputs['index.html'] = update_homepage((ROOT / 'index.html').read_text(), issue, data,
                                           json.loads(outputs[PATHS]))
    save(outputs)
    print(f'Built public profiles, permanent pages and the sitemap from {len(data)} published entries.')
