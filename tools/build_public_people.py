"""Build static profiles, a public directory and the sitemap from published credits."""
import hashlib
import json
import re
import unicodedata
from collections import defaultdict
from html import escape
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlencode, urlsplit, parse_qs
from urllib.request import urlopen
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SITE = 'https://oilandgas.eu.com'
FEED = 'https://mterm2026-559f9bf571b5.herokuapp.com/api/oilandgas/editor/browse'
OWNER = '<!-- Generated by build_public_people.py -->'
START = '<!-- Additional credited works: start -->'
END = '<!-- Additional credited works: end -->'
ZURIX_PAGE = '/m-zurix-mohamed.html'
SEPARATOR = re.compile(r'\s*[,;]\s*|\s+(?:and|&)\s+', re.I)
GROUPS = {'oil & gas editorial', 'oil and gas editorial', 'editorial team', 'anonymous',
          'unknown', 'n/a', 'et al.', 'et al', 'staff', 'editorial', 'various authors'}


def key(name):
    name = ' '.join(unicodedata.normalize('NFC', name).casefold().split())
    return re.sub(r'(?<!\w)([^\W\d_])\.(?=\s|$)', r'\1', name)


def public_name(name):
    return bool(name.strip() and key(name) not in GROUPS and '@' not in name
                and '://' not in name and not re.search(r'[<>]', name) and any(ch.isalpha() for ch in name))


def slug(name):
    plain = unicodedata.normalize('NFKD', name).encode('ascii', 'ignore').decode()
    return re.sub(r'[^a-z0-9]+', '-', plain.lower()).strip('-')[:65] or 'author'


def load_entries():
    entries = {}
    for kind in ('articles', 'publications'):
        page = 0
        while True:
            query = urlencode({'kind': kind, 'page': page, 'limit': 24})
            with urlopen(FEED + '?' + query, timeout=30) as response:
                listing = json.load(response)
            items, more = listing['items'], listing['more']
            if not isinstance(items, list) or not isinstance(more, bool) or (more and len(items) != 24):
                raise ValueError('Incomplete public listing')
            for item in items:
                ref = item['reference']
                if (item['kind'] != kind or not isinstance(ref, str) or not ref.strip()
                        or ref in entries or not isinstance(item['byline'], str)
                        or not isinstance(item['title'], str) or not item['title'].strip()):
                    raise ValueError(f'Invalid or duplicate public record: {ref}')
                entries[ref] = item
            if not more:
                break
            page += 1
    return entries


def reader_url(entry):
    return '/read.html?' + urlencode({'kind': entry['kind'], 'ref': entry['reference']})


def shell(title, description, url, main, profile_name=None):
    schema = ''
    if profile_name:
        data = {'@context': 'https://schema.org', '@type': 'ProfilePage', 'url': SITE + url,
                'mainEntity': {'@type': 'Person', '@id': SITE + url + '#person', 'name': profile_name}}
        payload = json.dumps(data, ensure_ascii=False).replace('<', r'\u003c')
        schema = f'<script type="application/ld+json">{payload}</script>'
    return f'''<!doctype html>
<html lang="en">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{escape(title)} | Oil &amp; Gas</title>
<meta name="description" content="{escape(description)}"><link rel="canonical" href="{escape(SITE + url)}">
<link rel="stylesheet" href="/browse.css"><link rel="stylesheet" href="/people.css">{schema}</head>
<body>{OWNER}
<header class="wrap"><div class="brand"><a href="/"><img src="/logo.png" alt="Oil &amp; Gas home"></a></div>
<nav class="nav people-nav" aria-label="Main navigation"><a href="/">Home</a>
<a href="/browse.html?kind=publications">Publications</a><a href="/browse.html?kind=articles">Articles</a>
<a href="/authors/">Authors &amp; contributors</a></nav></header>
<main class="people">{main}</main></body></html>
'''


def work_sections(works):
    sections = []
    for role, title in [('publications', 'Publications'), ('articles', 'Articles'), ('shared', 'Shared works')]:
        if not works.get(role):
            continue
        rows = []
        for entry in sorted(works[role], key=lambda e: (e.get('publishedAt') or '', e['reference']), reverse=True):
            url = escape(reader_url(entry))
            byline = escape(entry['byline'])
            desc = escape(entry.get('summary') or '')
            rows.append(f'<li><h3><a href="{url}">{escape(entry["title"])}</a></h3>'
                        f'<p class="byline">{byline}</p><p>{desc}</p></li>')
        sections.append(f'<section><h2>{title}</h2><ul class="works">{"".join(rows)}</ul></section>')
    return '\n'.join(sections)


class CuratedLinks(HTMLParser):
    def __init__(self):
        super().__init__()
        self.refs = set()

    def handle_starttag(self, tag, attrs):
        if tag == 'a':
            url = urlsplit(dict(attrs).get('href') or '')
            if url.path.lstrip('/') == 'read.html':
                self.refs.update(parse_qs(url.query).get('ref', []))


def extend_zurix_page(original, works):
    # Preserve the editor's selection, biography, design and already indexed URL.
    if START in original and END in original:
        before, rest = original.split(START, 1)
        original = before + rest.split(END, 1)[1]
    if original.count('</main>') != 1:
        raise ValueError('Expected one main section in the existing Zurix profile')
    curated = CuratedLinks()
    curated.feed(original)
    remaining = {k: [e for e in items if e['reference'] not in curated.refs]
                 for k, items in works.items()}
    block = START + '\n' + work_sections(remaining) + '\n' + END
    return original.replace('</main>', block + '</main>')


def make_outputs(entries, config, root=ROOT):
    profiles = config['profiles']
    # Public members are explicit editorial entries, never fetched from registration data.
    members = config['public_members']
    aliases = {}
    urls = {}
    names = {}
    bios = {}
    for identifier, info in list(profiles.items()) + [(m['id'], m) for m in members]:
        if (not re.fullmatch('[a-z0-9][a-z0-9-]*', identifier) or identifier == 'index'
                or identifier in names or not public_name(info['name'])):
            raise ValueError(f'Invalid profile configuration: {identifier}')
        names[identifier] = info['name']
        urls[identifier] = ZURIX_PAGE if identifier == 'zurix' else f'/authors/{identifier}.html'
        bios[identifier] = info.get('bio', '').strip()
        for value in [info['name'], *info.get('aliases', [])]:
            # If two people have the same name, require explicit per-record resolution.
            alias = key(value)
            aliases[alias] = identifier if alias not in aliases or aliases[alias] == identifier else None

    works = defaultdict(lambda: defaultdict(list))
    credits = {}
    indexable = {SITE + '/', SITE + '/authors/'}
    for page in ('contact.html', 'membership.html'):
        if (root / page).is_file():
            indexable.add(f'{SITE}/{page}')
    indexable.update(SITE + '/browse.html?kind=' + k for k in ('articles', 'publications'))
    overrides = config['credit_overrides']
    configured_ids = set(names)
    for ref, item in sorted(entries.items()):
        indexable.add(SITE + reader_url(item))
        byline = item['byline'].strip()
        listed = [name for group in re.split(r'[,;]', byline) if key(group) not in GROUPS
                  for name in SEPARATOR.split(group)]
        credit = {'authors': {}, 'shared': {}}
        seen = set()
        for role, labels in [('authors', listed), ('shared', [item.get('sharedBy') or ''])]:
            for raw in labels:
                label = raw.strip()
                if not public_name(label):
                    continue
                normalized = key(label)
                item_override = overrides.get(ref, {}).get(label)
                if item_override is not None:
                    if item_override not in configured_ids:
                        raise ValueError(f'Unknown profile for {ref}: {item_override}')
                    identifier = item_override
                elif normalized in aliases:
                    identifier = aliases[normalized]
                    if identifier is None:
                        continue
                else:
                    identifier = 'name:' + normalized
                    if identifier not in urls:
                        suffix = hashlib.sha256(normalized.encode()).hexdigest()[:12]
                        urls[identifier] = f'/authors/{slug(normalized)}-{suffix}.html'
                        names[identifier] = label
                credit[role][label] = urls[identifier]
                if identifier not in seen:
                    works[identifier][item['kind'] if role == 'authors' else 'shared'].append(item)
                    seen.add(identifier)
        credits[ref] = credit

    for member in members:
        if not bios[member['id']]:
            raise ValueError('A public member needs a short public biography')
        works[member['id']]  # Include the profile even before their first publication.
    outputs = {}
    people = sorted(works, key=lambda i: (key(names[i]), i))
    member_ids = {m['id'] for m in members}
    for identifier in people:
        url = urls[identifier]
        name = names[identifier]
        indexable.add(SITE + url)
        if identifier == 'zurix':
            continue
        if url[1:] in outputs:
            raise ValueError(f'Conflicting profile URL: {url}')
        credits_here = works[identifier]
        caption = 'Author' if credits_here.get('articles') or credits_here.get('publications') else (
            'Member' if identifier in member_ids else 'Contributor')
        bio = bios.get(identifier) or ''
        first_work = next((e['title'] for items in credits_here.values() for e in items), '')
        description = bio or f'{caption} {name}. {first_work}'
        main = f'<p class="eyebrow">{caption}</p><h1>{escape(name)}</h1>'
        if bio:
            main += f'<p>{escape(bio)}</p>'
        outputs[url[1:]] = shell(name, description, url, main + work_sections(credits_here), name)
    existing = root / ZURIX_PAGE[1:]
    if existing.is_file():
        indexable.add(SITE + ZURIX_PAGE)
        outputs[ZURIX_PAGE[1:]] = extend_zurix_page(existing.read_text(), works.get('zurix', {}))
    elif 'zurix' in works:
        raise ValueError('The existing indexed Zurix page is missing')
    rows = [f'<li><a href="{urls[i]}">{escape(names[i])}</a></li>' for i in people]
    outputs['authors/index.html'] = shell('Authors & contributors', 'Find authors, contributors and their published work on Oil & Gas.',
                                          '/authors/', '<h1>Authors &amp; contributors</h1><ul class="directory">' + ''.join(rows) + '</ul>')
    outputs['authors/credits.json'] = json.dumps(credits, ensure_ascii=False, sort_keys=True, indent=2) + '\n'
    if len(indexable) > 50000:
        raise ValueError('The sitemap must now be split into multiple files')
    xml = ET.Element('urlset', xmlns='http://www.sitemaps.org/schemas/sitemap/0.9')
    for url in sorted(indexable):
        ET.SubElement(ET.SubElement(xml, 'url'), 'loc').text = url
    ET.indent(xml)
    outputs['sitemap.xml'] = ET.tostring(xml, encoding='utf-8', xml_declaration=True).decode()
    return outputs


def save(outputs, root=ROOT):
    folder = root / 'authors'
    folder.mkdir(exist_ok=True)
    obsolete = [path for path in folder.glob('*.html') if path.relative_to(root).as_posix() not in outputs
                and OWNER in path.read_text()]
    for path in outputs:
        old = root / path
        if path.startswith('authors/') and path.endswith('.html') and old.exists() and OWNER not in old.read_text():
            raise ValueError(f'Existing hand-written page would be overwritten: {path}')
    for path, body in outputs.items():
        (root / path).write_text(body, encoding='utf-8')
    for path in obsolete:
        path.unlink()


if __name__ == '__main__':
    data = load_entries()
    cfg = json.loads((ROOT / 'tools/public-people.json').read_text())
    outputs = make_outputs(data, cfg)
    save(outputs)
    print(f'Built the public directory, author pages and sitemap from {len(data)} published entries.')
